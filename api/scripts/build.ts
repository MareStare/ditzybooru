import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import type { CoverageEntry } from '../src/coverage.ts';
import { operations } from '../src/index.ts';
import { schemas } from '../src/schemas/index.ts';

const root = fileURLToPath(new URL('..', import.meta.url));
const check = process.argv.includes('--check');

function sortKeys(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value)
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([k, v]) => [k, sortKeys(v)]),
    );
  }
  return value;
}

const coveragePath = `${root}coverage.json`;
const coverage = JSON.parse(readFileSync(coveragePath, 'utf8')) as Record<string, CoverageEntry>;
const operationsByRoute = new Map<string, string[]>();

const paths: Record<string, Record<string, unknown>> = {};
for (const op of operations) {
  const params = (op.params ?? []).map(p => ({
    name: p.name,
    in: p.in,
    required: p.in === 'path' ? true : (p.required ?? false),
    ...(p.description ? { description: p.description } : {}),
    schema: p.schema.json,
  }));
  const entry: Record<string, unknown> = {
    operationId: op.operationId,
    summary: op.summary,
    tags: op.tags,
    ...(params.length ? { parameters: params } : {}),
    ...(op.body ? { requestBody: { required: true, content: { 'application/json': { schema: op.body.json } } } } : {}),
    responses: {
      '200': {
        description: 'Success',
        content: { 'application/json': { schema: op.response.json } },
      },
      default: {
        description: 'Error',
        content: { 'application/json': { schema: { $ref: '#/components/schemas/Error' } } },
      },
    },
    'x-philomena': op.philomena,
    ...(op.examples ? { 'x-examples': op.examples } : {}),
  };
  (paths[op.path] ??= {})[op.method] = entry;
  for (const route of op.philomena.routes) {
    if (!coverage[route]) throw new Error(`${op.operationId}: unknown route "${route}"`);
    operationsByRoute.set(route, [...(operationsByRoute.get(route) ?? []), op.operationId]);
  }
}

const document = sortKeys({
  openapi: '3.1.0',
  info: {
    title: 'Ditzybooru API',
    version: '0.1.0',
    description: 'Generated by api/scripts/build.ts. Do not edit by hand.',
  },
  servers: [{ url: '/api/v1' }],
  paths,
  components: {
    schemas: Object.fromEntries(Object.entries(schemas).map(([k, v]) => [k, v.json])),
  },
});
const output = JSON.stringify(document, null, 2) + '\n';

for (const [key, entry] of Object.entries(coverage)) {
  const ops = operationsByRoute.get(key) ?? [];
  entry.operations = ops;
  if (ops.length > 0 && entry.status === 'todo') entry.status = 'mapped';
  else if (ops.length === 0 && entry.status === 'mapped') entry.status = 'todo';
}
const coverageOutput = JSON.stringify(coverage, null, 2) + '\n';

if (check) {
  const stale =
    readFileSync(`${root}openapi.json`, 'utf8') !== output || readFileSync(coveragePath, 'utf8') !== coverageOutput;
  if (stale) {
    console.error('api/openapi.json or coverage.json is stale; run `pnpm --filter api run build`');
    process.exit(1);
  }
} else {
  writeFileSync(`${root}openapi.json`, output);
  writeFileSync(coveragePath, coverageOutput);
  console.log(`${operations.length} operations, ${Object.keys(paths).length} paths`);
}
